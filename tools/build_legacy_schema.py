"""Convert this project's MariaDB table definitions; data is never emitted here."""
from pathlib import Path
import re
import sys

def build(path):
    source = Path(path).read_text(encoding='utf-8-sig')
    statements = ['-- MariaDB business schema converted to PostgreSQL. No user data.', 'begin;']
    for m in re.finditer(r'CREATE TABLE `(\w+)`\s*\((.*?)\) ENGINE', source, re.S):
        table = m[1]
        if table.startswith(('vw_', 'v_')): continue
        columns = []
        for line in m[2].splitlines():
            c = re.match(r'\s*`(\w+)`\s+(.*)', line)
            if not c: continue
            name, definition = c.groups()
            if table == 'users' and name in ('password_hash','security_question','security_answer'): continue
            if definition.startswith(('int(', 'bigint(', 'tinyint(')): kind = 'bigint'
            elif definition.startswith('decimal('): kind = re.match(r'decimal\([^)]*\)', definition)[0]
            elif definition.startswith('varchar('): kind = re.match(r'varchar\([^)]*\)', definition)[0]
            elif definition.startswith('enum('): kind = 'text'
            elif definition.startswith('longtext') and 'json_valid' in definition: kind = 'jsonb'
            elif definition.startswith(('timestamp','datetime')): kind = 'timestamptz'
            elif definition.startswith('date '): kind = 'date'
            elif definition.startswith('time '): kind = 'time'
            else: kind = 'text'
            is_pk = not columns
            result = f'  "{name}" {kind}'
            if is_pk: result += ' generated by default as identity primary key'
            elif 'NOT NULL' in definition: result += ' not null'
            default = re.search(r"DEFAULT (NULL|'[^']*'|-?\d+(?:\.\d+)?|current_timestamp\(\))", definition)
            if default and not is_pk:
                value = default[1]
                if value == 'current_timestamp()': value = 'now()'
                result += ' default ' + value
            if definition.startswith('enum('):
                values = re.match(r'enum\((.*?)\)', definition)[1]
                result += f' check ("{name}" in ({values}))'
            columns.append(result)
        statements.append(f'create table public.{table} (\n'+',\n'.join(columns)+'\n);')
        statements.append(f'alter table public.{table} enable row level security;\nrevoke all on public.{table} from anon, authenticated;')
    # Relationships are retained; ON DELETE defaults to RESTRICT to protect records.
    for block in re.finditer(r'ALTER TABLE `(\w+)`\s+(.*?);', source, re.S):
        table = block[1]
        if table.startswith(('vw_', 'v_')): continue
        for fk in re.finditer(r'CONSTRAINT `(\w+)` FOREIGN KEY \(`(\w+)`\) REFERENCES `(\w+)` \(`(\w+)`\)',block[2]):
            name, col, target, target_col = fk.groups()
            statements.append(f'alter table public.{table} add constraint {name} foreign key ({col}) references public.{target}({target_col});')
    statements.append('alter table public.profiles add column legacy_user_id bigint unique references public.users(user_id);')
    statements.append('commit;')
    return '\n\n'.join(statements)+'\n'

if __name__ == '__main__':
    Path(sys.argv[2]).write_text(build(sys.argv[1]), encoding='utf-8')
